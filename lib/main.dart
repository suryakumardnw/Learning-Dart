void main() {
  print(add(5, 5));
  print(subtract(8, 5));
  print(multiply(4, 4));
  print(divide(100, 25));
}

int add(int a, int b) {
  return a + b;
}

int subtract(int a, int b) {
  return a - b;
}

int multiply(int a, int b) {
  return a * b;
}

double divide(int a, int b) {
  return a / b;
}
